#!/usr/bin/env python3
"""Generates kernel/symtab.c from `nm -n` on a first-pass kernel.elf link
(kernel.elf.pass1, built from every object except kernel/symtab.o itself --
see the Makefile). Text symbols only (nm type t/T), sorted ascending by
address (nm -n's own order, kept as-is), deduplicated by address so the
binary search in kernel/backtrace.c never has to pick between ties.

Deterministic: same kernel.elf.pass1 bytes always produce the same table,
so a clean build is reproducible and the file never needs to be committed
(see .gitignore, same relationship drivers/version.h has to VERSION).

Usage: gen_symtab.py <kernel.elf.pass1> <out kernel/symtab.c>
"""
import subprocess, sys

def main():
    if len(sys.argv) != 3:
        print("usage: gen_symtab.py <elf> <out.c>", file=sys.stderr)
        return 1
    elf, out = sys.argv[1], sys.argv[2]
    nm = subprocess.run(["nm", "-n", elf], capture_output=True, text=True, check=True)
    entries = []
    seen_addr = set()
    for line in nm.stdout.splitlines():
        parts = line.split()
        if len(parts) != 3:
            continue
        addr_s, typ, name = parts
        if typ not in ("t", "T"):
            continue
        try:
            addr = int(addr_s, 16)
        except ValueError:
            continue
        if addr in seen_addr:
            continue
        seen_addr.add(addr)
        # A C string literal, escaped; symbol names here are plain C
        # identifiers (clang doesn't mangle), so this is just a safety net.
        esc = name.replace("\\", "\\\\").replace('"', '\\"')
        entries.append((addr, esc))
    entries.sort(key=lambda e: e[0])

    with open(out, "w") as f:
        f.write("/* GENERATED by tools/gen/gen_symtab.py from nm -n on kernel.elf.pass1. */\n")
        f.write('#include "symtab.h"\n\n')
        f.write("const struct sym_entry kernel_symtab[] = {\n")
        for addr, name in entries:
            f.write('    {0x%08xu, "%s"},\n' % (addr, name))
        f.write("};\n")
        f.write("const unsigned int kernel_symtab_count = %d;\n" % len(entries))
    return 0

if __name__ == "__main__":
    sys.exit(main())
