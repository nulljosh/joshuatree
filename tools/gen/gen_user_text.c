/* Bakes the antialiased glyph atlas user/libjt/text.c draws from.
 *
 * Host program, built and run by the Makefile rule for user/libjt/aafont.h.
 * It rasterizes through the kernel's own drivers/ttf.c (stb_truetype over the
 * same embedded DejaVu blobs the in-kernel apps use), so ring-3 text is the
 * same glyphs from the same source, only pre-rendered for the few sizes and
 * the glyph range a flat ring-3 image (28KB when this was sized, 128KB now) can afford: a body size in
 * regular and bold, and a display size for digits. Coverage is packed to
 * 4 bits (16 steps is still a smooth edge ramp). Latin-1 degree (0xB0) is
 * included.
 *
 * The mono face (DejaVu Sans Mono, ASCII, one size) goes to its own header,
 * aamono.h, with its own pool, so only apps that link user/libjt/mono.o pay for it.
 *
 * Usage: gen_user_text <aafont.h> <aamono.h>
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "../../drivers/ttf.h"

#define BODY_PX 14.0f
#define DISP_PX 56.0f
#define MONO_PX 13.5f /* DejaVu Sans Mono advance rounds to 8 px: the terminal's cell */

typedef struct { const char *name; ttf_face_t face; float px; const char *set; } face_t;

int main(int argc, char **argv) {
    if (argc != 3) { fprintf(stderr, "usage: %s <aafont.h> <aamono.h>\n", argv[0]); return 1; }
    FILE *o = fopen(argv[1], "w");
    if (!o) { perror(argv[1]); return 1; }
    static char body[200], disp[40];
    int nb = 0, nd = 0;
    for (int c = 0x20; c <= 0x7E; c++) body[nb++] = (char)c;
    body[nb++] = (char)0xB0;
    for (int c = '0'; c <= '9'; c++) disp[nd++] = (char)c;
    disp[nd++] = '-'; disp[nd++] = (char)0xB0; disp[nd++] = ' ';
    face_t faces[3] = {
        {"BODY", TTF_FACE_SANS, BODY_PX, body},
        {"BOLD", TTF_FACE_SANS_BOLD, BODY_PX, body},
        {"DISPLAY", TTF_FACE_SANS, DISP_PX, disp},
    };
    fprintf(o, "/* Generated by tools/gen/gen_user_text.c from drivers/dejavu_font.h and\n"
               "   drivers/dejavu_bold_font.h (DejaVu Sans, public domain / Bitstream Vera).\n"
               "   Do not edit by hand. */\n#ifndef AAFONT_H\n#define AAFONT_H\n\n");
    /* glyph record: first, last handled by tables; data is 4-bit packed rows. */
    static unsigned char pool[40000]; int pn = 0;
    fprintf(o, "struct aa_glyph { unsigned short off; unsigned char w, h; signed char xoff, yoff; unsigned char adv; };\n");
    struct { int ascent, height; } met[3];
    for (int f = 0; f < 3; f++) {
        ttf_font_t *font = ttf_load_face(faces[f].face);
        const char *set = faces[f].set; int n = (int)strlen(set);
        met[f].ascent = ttf_ascent(font, faces[f].px);
        met[f].height = (int)(faces[f].px * 1.17f + 0.5f);
        fprintf(o, "static const struct aa_glyph aa_%s_glyphs[] = {\n", faces[f].name);
        for (int i = 0; i < n; i++) {
            ttf_glyph_t g;
            unsigned cp = (unsigned char)set[i];
            if (ttf_glyph(font, cp, faces[f].px, &g)) return 1;
            int off = pn, bits = 0;
            for (int p = 0; p < g.width * g.height; p++) {
                int v = (g.coverage[p] + 8) / 17; if (v > 15) v = 15;
                if (!(p & 1)) pool[pn] = (unsigned char)(v << 4); else pool[pn++] |= (unsigned char)v;
                bits++;
            }
            if (bits & 1) pn++;
            fprintf(o, "    {%d,%d,%d,%d,%d,%d},\n", g.width ? off : 0, g.width, g.height, g.xoff, g.yoff, g.advance);
            ttf_free_glyph(&g);
        }
        fprintf(o, "};\n");
    }
    fprintf(o, "static const unsigned char aa_pool[%d] = {", pn);
    for (int i = 0; i < pn; i++) fprintf(o, "%s%d,", i % 24 ? "" : "\n    ", pool[i]);
    fprintf(o, "\n};\n");
    for (int f = 0; f < 3; f++) {
        fprintf(o, "#define AA_%s_ASCENT %d\n#define AA_%s_HEIGHT %d\n#define AA_%s_N %d\n", faces[f].name, met[f].ascent, faces[f].name, met[f].height, faces[f].name, (int)strlen(faces[f].set));
    }
    fprintf(o, "/* display set: 0-9, '-', degree, space */\n#endif\n");
    fclose(o);

    /* aamono.h: ASCII 0x20..0x7E in DejaVu Sans Mono. Same record and 4-bit packing. */
    o = fopen(argv[2], "w");
    if (!o) { perror(argv[2]); return 1; }
    ttf_font_t *mf = ttf_load_face(TTF_FACE_MONO);
    fprintf(o, "/* Generated by tools/gen/gen_user_text.c from drivers/dejavu_mono_font.h\n"
               "   (DejaVu Sans Mono, public domain / Bitstream Vera). Do not edit by hand. */\n"
               "#ifndef AAMONO_H\n#define AAMONO_H\n\n");
    static unsigned char mpool[12000]; int mn = 0;
    fprintf(o, "struct aam_glyph { unsigned short off; unsigned char w, h; signed char xoff, yoff; unsigned char adv; };\n");
    fprintf(o, "static const struct aam_glyph aa_MONO_glyphs[] = {\n");
    for (int c = 0x20; c <= 0x7E; c++) {
        ttf_glyph_t g;
        if (ttf_glyph(mf, (unsigned)c, MONO_PX, &g)) return 1;
        int off = mn, bits = 0;
        for (int p = 0; p < g.width * g.height; p++) {
            int v = (g.coverage[p] + 8) / 17; if (v > 15) v = 15;
            if (!(p & 1)) mpool[mn] = (unsigned char)(v << 4); else mpool[mn++] |= (unsigned char)v;
            bits++;
        }
        if (bits & 1) mn++;
        fprintf(o, "    {%d,%d,%d,%d,%d,%d},\n", g.width ? off : 0, g.width, g.height, g.xoff, g.yoff, g.advance);
        ttf_free_glyph(&g);
    }
    fprintf(o, "};\nstatic const unsigned char aa_mono_pool[%d] = {", mn);
    for (int i = 0; i < mn; i++) fprintf(o, "%s%d,", i % 24 ? "" : "\n    ", mpool[i]);
    fprintf(o, "\n};\n#define AA_MONO_ASCENT %d\n#define AA_MONO_HEIGHT %d\n#define AA_MONO_ADV %d\n#endif\n",
            ttf_ascent(mf, MONO_PX), (int)(MONO_PX * 1.17f + 0.5f), 8);
    fclose(o);
    return 0;
}
