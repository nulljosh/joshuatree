#!/usr/bin/env python3
"""The Joshua Tree type system, one source. Generates the token block in landing/index.html and docs/ARCHITECTURE.md, and with
--snap rewrites every font-size in the landing's CSS onto the scale (run once; tools/checks/type-grid-check.py keeps it so).

The constraints, in order of authority:
  1. Everything sits on a 4 px baseline grid: line heights, spacing and padding are multiples of 4.
  2. Nine sizes and no others: 11 13 15 17 22 28 36 48 64 (a 1.25 ratio, rounded to whole pixels, then the grid).
  3. Line height is 1.3 times the size, rounded up to the grid: 16 20 20 24 32 40 48 64 84.
  4. Tracking tightens as type grows (Apple's rule of thumb): +0.01em at 11, 0 at 13 to 15, -0.01em at 17 to 22, -0.02em above.
  5. Weights have jobs: 400 reads, 500 labels, 600 leads, 700 headlines. Display optical size from 22 px up, Text below.
  6. Padding and gaps come from one ladder: 4 8 12 16 24 32 48 64 96.

    python3 tools/gen/typetokens.py [--snap] [--check]
"""
import math, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SIZES = [11, 13, 15, 17, 22, 28, 36, 48, 64]
SPACE = [4, 8, 12, 16, 24, 32, 48, 64, 96]
NAMES = {11: "caption", 13: "footnote", 15: "callout", 17: "body", 22: "title3", 28: "title2", 36: "title1", 48: "large", 64: "hero"}
FACES = [("Tree Sans", "Regular", 400, "TreeSans-Regular"), ("Tree Sans", "Medium", 500, "TreeSans-Medium"),
         ("Tree Sans", "SemiBold", 600, "TreeSans-SemiBold"), ("Tree Sans", "Bold", 700, "TreeSans-Bold"),
         ("Tree Sans Display", "SemiBold", 600, "TreeSansDisplay-SemiBold"), ("Tree Sans Display", "Bold", 700, "TreeSansDisplay-Bold")]
START, END = "/* type-tokens:start (generated by tools/gen/typetokens.py, do not edit) */", "/* type-tokens:end */"


def lh(size): return int(math.ceil(size * 1.3 / 4.0)) * 4
def tracking(size): return "0.01em" if size <= 11 else "0" if size <= 15 else "-0.01em" if size <= 22 else "-0.02em"
def snap(px):
    best = min(SIZES, key=lambda s: (abs(s - px), -s))     # the nearest step; a tie goes up, small type errs large
    return best


def css_block():
    o = [START]
    for fam, style, w, file in FACES:
        o.append(f'@font-face{{font-family:"{fam}";src:url(fonts/{file}.woff2) format("woff2");font-weight:{w};font-style:normal;font-display:swap}}')
    o.append(':root{--font:"Tree Sans",-apple-system,BlinkMacSystemFont,"Helvetica Neue",Helvetica,Arial,sans-serif;--font-display:"Tree Sans Display","Tree Sans",-apple-system,BlinkMacSystemFont,"Helvetica Neue",Helvetica,Arial,sans-serif;--u:4px;')
    for s in SIZES:
        o.append(f'--t{s}:{s}px;--lh{s}:{lh(s)}px;--tr{s}:{tracking(s)};')
    o.append(" ".join(f"--s{v}:{v}px;" for v in SPACE))
    o.append('}')
    o.append('body{font-family:var(--font);font-feature-settings:"kern","liga","calt";font-kerning:normal;text-rendering:optimizeLegibility;-webkit-font-smoothing:antialiased}')
    o.append('h1,h2,h3,.display{font-family:var(--font-display);text-wrap:balance}')
    o.append('p,li,.sub{text-wrap:pretty}')
    o.append(END)
    return "\n".join(o)


def type_md():
    rows = "\n".join(f"| {NAMES[s]} | {s} | {lh(s)} | {tracking(s)} | {'Display' if s >= 22 else 'Text'} |" for s in SIZES)
    return f"""The face is **Tree Sans**, built by `tools/fonts/treesans/build.py` from Inter 4.1 (SIL OFL 1.1) and renamed as the licence asks.
Two optical sizes: **Text** (opsz 14, open and generously fitted) below 22 px, **Display** (opsz 32, tighter) from 22 px up.
Proportional by default, kerned, with tabular digits one feature away (`font-variant-numeric: tabular-nums`).

### Constraints

1. A **4 px baseline grid**. Line heights, gaps and padding are all multiples of 4.
2. **Nine sizes**, a 1.25 ratio rounded to whole pixels. No tenth size.
3. **Line height** is 1.3 times the size, rounded up to the grid.
4. **Tracking** tightens as type grows: +0.01em at 11, 0 at 13 to 15, -0.01em at 17 to 22, -0.02em above.
5. **Weights have jobs**: 400 reads, 500 labels, 600 leads, 700 headlines.
6. **Space** comes from one ladder: {" ".join(map(str, SPACE))}.

### Scale

| Role | Size px | Line px | Tracking | Cut |
|---|---|---|---|---|
{rows}

### Font metrics

Every vertical metric is a multiple of 1/16 em: ascent 15, descent 4, line gap 0, a 19/16 em line box. Glyph spacing is the font's own, with
its kerning (GPOS `kern`) on. Alternates frozen into the default letters: the tailed `l`, the serifed capital `I` and round quotes and commas, so
`I`, `l` and `1` never read alike on a small screen.
"""


DECL = re.compile(r"([{;]\s*)font-size\s*:\s*([0-9.]+)px")
def snap_css(text):
    out, pos = [], 0
    for m in re.finditer(r"<style[^>]*>(.*?)</style>", text, re.S):
        css = m.group(1)
        def rule(r):
            body = r.group(2)
            sizes = [float(x.group(2)) for x in DECL.finditer("{" + body)]
            if not sizes: return r.group(0)
            s = snap(sizes[0]); body2 = DECL.sub(lambda x: f"{x.group(1)}font-size:var(--t{snap(float(x.group(2)))})", "{" + body)[1:]
            if "line-height" in body2:
                body2 = re.sub(r"line-height\s*:\s*[^;}]+", f"line-height:var(--lh{s})", body2, 1)
            else:
                body2 = body2.rstrip().rstrip(";") + f";line-height:var(--lh{s})"
            if "letter-spacing" not in body2 and "text-transform" not in body2:
                body2 += f";letter-spacing:var(--tr{s})"
            return r.group(1) + "{" + body2 + "}"
        css2 = re.sub(r"([^{}@]+)\{([^{}]*)\}", lambda r: rule(type("R", (), {"group": lambda self, i, r=r: ("%s" % r.group(1) if i == 1 else r.group(2) if i == 2 else r.group(0))})()), css)
        out.append((m.start(1), m.end(1), css2))
    for a, b, c in reversed(out): text = text[:a] + c + text[b:]
    return text


def main():
    p = os.path.join(ROOT, "landing", "index.html"); t = open(p).read()
    if "--snap" in sys.argv: t = snap_css(t)
    blk = css_block()
    if START in t: t = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda m: blk, t, flags=re.S)
    else: t = t.replace("<style>", "<style>\n" + blk + "\n", 1)
    t = re.sub(r"font-family:\s*-apple-system, BlinkMacSystemFont, \"Helvetica Neue\", Helvetica, Arial, sans-serif;", "font-family: var(--font);", t)
    open(p, "w").write(t)
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__))); import docblock; docblock.write("type", type_md())
    print("typetokens: landing/index.html and the type block in docs/ARCHITECTURE.md written")


if __name__ == "__main__":
    main()
