#!/usr/bin/env python3
"""Pack Samantha's face for the ring-3 chat app into user/samantha_face.h.

Same source as the kernel's chat face (landing/face/idle-*.jpg and
talk-*.jpg from tools/gen/face_frames.py), so there is one set of frames.
Downsampled to 60x60 RGB332 and thinned so the whole face stays near 60 KB
of the app's 128 KB image: every 3rd idle frame (8 of 24), every 6th talk
frame (8 of 48). Each talk frame carries its mouth openness (the kernel's
variance measure, scaled 0..255) so the app can pick mouths by loudness.
"""
import os
from PIL import Image
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
D = os.path.join(ROOT, "landing", "face")
S = 60

def openness(im):
    im = im.convert("L"); w, h = im.size
    px = [im.getpixel((x, y)) for y in range(int(h*.58), int(h*.74), 2) for x in range(int(w*.40), int(w*.60), 2)]
    m = sum(px) / len(px)
    return sum((p - m) ** 2 for p in px) / len(px)

def pack(im):
    im = im.convert("RGB").resize((S, S), Image.LANCZOS)
    return bytes((r & 0xE0) | ((g >> 3) & 0x1C) | (b >> 6) for r, g, b in im.getdata())

def load(kind, step):
    out = []
    for i in range(0, 48 if kind == "talk" else 24, step):
        p = os.path.join(D, f"{kind}-{i}.jpg")
        if os.path.exists(p): out.append(Image.open(p))
    return out

idle, talk = load("idle", 3), load("talk", 6)
ops = [openness(t) for t in talk]; hi = max(ops) or 1
rows = []
def arr(name, frames):
    s = f"static const unsigned char {name}[{len(frames)}][{S*S}] = {{\n"
    for f in frames:
        b = pack(f); s += "{" + ",".join(str(v) for v in b) + "},\n"
    return s + "};\n"
h = "/* Generated by tools/gen/face_user.py from landing/face. Do not edit. */\n"
h += f"#define UFACE_SIDE {S}\n#define UFACE_IDLE_N {len(idle)}\n#define UFACE_TALK_N {len(talk)}\n"
h += arr("uface_idle", idle) + arr("uface_talk", talk)
h += "static const unsigned char uface_open[UFACE_TALK_N] = {" + ",".join(str(int(255 * o / hi)) for o in ops) + "};\n"
open(os.path.join(ROOT, "user", "samantha_face.h"), "w").write(h)
print(len(idle), len(talk))
