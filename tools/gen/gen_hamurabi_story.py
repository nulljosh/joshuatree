#!/usr/bin/env python3
"""Generate user/hamurabi_story.h from art/hamurabi/story.json"""
import json
import sys

def escape_string(s):
    """Escape a string for C"""
    return s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\r', '\\r')

def main():
    story_path = 'art/hamurabi/story.json'
    output_path = 'user/hamurabi_story.h'

    with open(story_path) as f:
        story = json.load(f)

    with open(output_path, 'w') as out:
        out.write('/* Generated by tools/gen/gen_hamurabi_story.py. Do not edit by hand. */\n')
        out.write('#ifndef HAMURABI_STORY_H\n')
        out.write('#define HAMURABI_STORY_H\n\n')

        # Intro
        out.write('static const char hamurabi_intro_title[] = "')
        out.write(escape_string(story['intro']['title']))
        out.write('";\n')
        out.write('static const char hamurabi_intro_text[] = "')
        out.write(escape_string(story['intro']['text']))
        out.write('";\n\n')

        # Interludes
        for year, interlude in story['interludes'].items():
            out.write(f'static const char hamurabi_interlude_{year}_title[] = "')
            out.write(escape_string(interlude['title']))
            out.write('";\n')
            out.write(f'static const char hamurabi_interlude_{year}_text[] = "')
            out.write(escape_string(interlude['text']))
            out.write('";\n')
        out.write('\n')

        # Omens
        out.write('static const char hamurabi_omen_ids[] = ')
        omen_ids = [f'"{escape_string(o["id"])}"' for o in story['omens']]
        out.write(' '.join(omen_ids) + ';\n')

        out.write('#endif\n')

    print(f'Generated {output_path}')

if __name__ == '__main__':
    main()
