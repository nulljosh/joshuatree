#!/usr/bin/env python3
"""Turns art/hamurabi/story.json into user/hamurabi_story.h, plain C data for the Hamurabi app.

Run from the repo root: python3 tools/gen/gen_hamurabi_story.py
Every word and number of the story is in the JSON; this file only changes its shape.
A gamble's chance is written as the integer ceil(p * 2^53), which is exactly what the other ports
test a 53-bit draw against (see hamurabi_rng_below in user/hamurabi_rules.h)."""
import json, math, os
from fractions import Fraction

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
GRADES = ["F", "C", "B", "A+"]  # the order hamurabi_grade() returns 0..3


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def thr(p):
    return math.ceil(Fraction(p) * 2**53)


def choice_c(ch):
    g = ch.get("gamble")
    return "{ %s, %s, %d, %d, %d, %d, %d, %d, %d, %d, %dULL, %d, %s }" % (
        c_str(ch["label"]), c_str(ch["then"]),
        ch.get("grain", 0), ch.get("acres", 0), ch.get("acresPct", 0), ch.get("people", 0),
        ch.get("yieldBonus", 0), 1 if ch.get("guard") else 0, 1 if ch.get("peek") else 0,
        1 if g else 0, thr(g["chance"]) if g else 0, g.get("acres", 0) if g else 0, c_str(g["then"]) if g else '""')


def main():
    story = json.load(open(os.path.join(ROOT, "art", "hamurabi", "story.json")))
    out = []
    w = out.append
    w("/* Generated by tools/gen/gen_hamurabi_story.py from art/hamurabi/story.json. Do not edit by hand. */")
    w("#ifndef HAMURABI_STORY_H\n#define HAMURABI_STORY_H\n")
    w("typedef struct {")
    w("    const char *label, *then;")
    w("    int grain, acres, acres_pct, people, yield_bonus, guard, peek;")
    w("    int has_gamble;")
    w("    unsigned long long gamble_thr; /* ceil(chance * 2^53) */")
    w("    int gamble_acres;")
    w("    const char *gamble_then;")
    w("} hamurabi_choice;\n")
    w("typedef struct {")
    w("    const char *id, *title, *text;")
    w("    int needs_grain, needs_acres, needs_people;")
    w("    hamurabi_choice choice[2];")
    w("} hamurabi_omen;\n")
    w("typedef struct { int year; const char *title, *text; } hamurabi_interlude;\n")

    w("static const char hamurabi_intro_title[] = %s;" % c_str(story["intro"]["title"]))
    w("static const char hamurabi_intro_text[] = %s;\n" % c_str(story["intro"]["text"]))

    inter = sorted(story["interludes"].items(), key=lambda kv: int(kv[0]))
    w("#define HAMURABI_INTERLUDES %d" % len(inter))
    w("static const hamurabi_interlude hamurabi_interludes[HAMURABI_INTERLUDES] = {")
    for year, c in inter:
        w("    { %d, %s, %s }," % (int(year), c_str(c["title"]), c_str(c["text"])))
    w("};\n")

    w("/* The ending line for each grade, indexed like hamurabi_grade(): F, C, B, A+. */")
    w("static const char *const hamurabi_epilogues[4] = {")
    for g in GRADES:
        w("    %s," % c_str(story["epilogues"][g]))
    w("};\n")

    w("/* A tip for years 1 to 4, indexed by year - 1. */")
    w("static const char *const hamurabi_hints[4] = {")
    for y in range(1, 5):
        w("    %s," % c_str(story["hints"][str(y)]))
    w("};\n")

    omens = story["omens"]
    for o in omens:
        assert len(o["choices"]) == 2, o["id"]
    w("#define HAMURABI_OMENS %d" % len(omens))
    w("static const hamurabi_omen hamurabi_omens[HAMURABI_OMENS] = {")
    for o in omens:
        n = o.get("needs", {})
        w("    { %s, %s, %s," % (c_str(o["id"]), c_str(o["title"]), c_str(o["text"])))
        w("      %d, %d, %d," % (n.get("grain", 0), n.get("acres", 0), n.get("people", 0)))
        w("      { %s," % choice_c(o["choices"][0]))
        w("        %s } }," % choice_c(o["choices"][1]))
    w("};\n")
    w("#endif")
    path = os.path.join(ROOT, "user", "hamurabi_story.h")
    open(path, "w").write("\n".join(out) + "\n")
    print("wrote", os.path.relpath(path, ROOT))


if __name__ == "__main__":
    main()
