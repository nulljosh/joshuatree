#!/usr/bin/env python3
"""Generates drivers/jpeg_testdata.h: real, photographic JPEG files built
from the kernel's own baked wallpaper (drivers/wallpaper.h, a real NPS
photo, the same source drivers/png_testdata.h already crops), re-encoded
through PIL at several quality/chroma-subsampling combinations so every
in-scope path (4:4:4, 4:2:0, grayscale, a range of quantization strengths)
gets real coverage, not a synthetic single-color fixture.

Unlike PNG (lossless, so PIL's decode of a hand-built file is a bit-exact
oracle), JPEG is lossy: no independent decoder, including PIL/libjpeg, is
bit-exact with this kernel's own IDCT/upsampling choices, and the two are
not expected to match byte-for-byte. This script embeds the JPEG bytes
plus PIL's own RGB decode of them (the "reference" tools/checks/
jpeg-host-check.sh compares against within a documented tolerance,
because it's genuinely lossy, not a bug). It does NOT try to bake a
kernel-decode oracle hash here (chicken-and-egg: the only "host decode"
worth trusting bit-for-bit against the freestanding build is this exact
same C source compiled natively, which tools/checks/jpeg-check.sh derives
fresh at check time by actually running tools/jpeg-host, not a value
frozen here that could go stale)."""
import re, sys, io, os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
hdr = open(f'{ROOT}/drivers/wallpaper.h').read()
W = int(re.search(r'#define WALLPAPER_W (\d+)', hdr).group(1))
H = int(re.search(r'#define WALLPAPER_H (\d+)', hdr).group(1))
body = hdr[hdr.index('{') + 1:hdr.rindex('}')]
wall = bytes(int(t) for t in body.replace('\n', '').split(',') if t.strip())
assert len(wall) == W * H * 3, (len(wall), W * H * 3)


def crop(x0, y0, w, h):
    rows = bytearray()
    for y in range(h):
        for x in range(w):
            i = ((y0 + y) * W + (x0 + x)) * 3
            rows += wall[i:i + 3]
    return bytes(rows)


# name, x0, y0, w, h, quality, PIL subsampling (0=4:4:4, 2=4:2:0), gray
images = [
    ('photo_q90_420', 320, 180, 96, 64, 90, 2, False),
    ('photo_q75_444', 40, 400, 64, 48, 75, 0, False),
    ('photo_q50_420', 600, 20, 80, 56, 50, 2, False),
    ('photo_q95_444', 100, 300, 48, 48, 95, 0, False),
    ('gray_q85_420', 200, 250, 72, 56, 85, 2, True),
]

out = ['#ifndef JPEG_TESTDATA_H', '#define JPEG_TESTDATA_H',
       '/* Generated by tools/gen/gen_jpeg_testdata.py from drivers/wallpaper.h.',
       '   Real photographic JPEGs (crops of the baked wallpaper) re-encoded by',
       '   PIL at several quality/subsampling settings. Do not hand-edit. */']

for name, x0, y0, w, h, q, subs, gray in images:
    raw = crop(x0, y0, w, h)
    im = Image.frombytes('RGB', (w, h), raw)
    if gray:
        im = im.convert('L')
    buf = io.BytesIO()
    if gray:
        im.save(buf, format='JPEG', quality=q)
    else:
        im.save(buf, format='JPEG', quality=q, subsampling=subs)
    jpg = buf.getvalue()

    # PIL's own reference decode of the exact bytes being embedded, used
    # by jpeg-host-check.sh's tolerance comparison, not for an exact match.
    ref_im = Image.open(io.BytesIO(jpg))
    ref_im = ref_im.convert('L' if gray else 'RGB')
    assert ref_im.size == (w, h)
    ref = ref_im.tobytes()
    ch = 1 if gray else 3
    assert len(ref) == w * h * ch

    print(f'{name}: {w}x{h} {"GRAY" if gray else ("444" if subs == 0 else "420")} '
          f'q={q} jpeg={len(jpg)}B')
    up = name.upper()
    out.append(f'#define JPEGT_{up}_W {w}')
    out.append(f'#define JPEGT_{up}_H {h}')
    out.append(f'#define JPEGT_{up}_CH {ch}')
    out.append(f'static const unsigned char jpegt_{name}[{len(jpg)}] = {{')
    for i in range(0, len(jpg), 24):
        out.append(','.join(str(b) for b in jpg[i:i + 24]) + ',')
    out.append('};')
    out.append(f'static const unsigned char jpegt_{name}_pilref[{len(ref)}] = {{')
    for i in range(0, len(ref), 24):
        out.append(','.join(str(b) for b in ref[i:i + 24]) + ',')
    out.append('};')

out.append('#endif')
open(f'{ROOT}/drivers/jpeg_testdata.h', 'w').write('\n'.join(out) + '\n')
print('wrote drivers/jpeg_testdata.h')
