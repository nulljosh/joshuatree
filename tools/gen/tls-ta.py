#!/usr/bin/env python3
"""Turns PEM certificates into BearSSL trust anchors as a C header, at build time.

    tools/gen/tls-ta.py out.h cert1.pem cert2.pem ...

Each certificate becomes one br_x509_trust_anchor: its subject DN (DER, as the engine compares it against the
issuer of the next certificate down) and its public key (RSA n/e, or an EC curve and point). No network, no
OpenSSL: a small DER walker is all it takes. The arm64 Makefile runs it over arch/arm64/certs/*.pem plus
whatever TLS_TA= names (the check script's throwaway server cert). Run with no arguments for a self-test.
"""
import base64, re, sys

def tlv(b, i):
    """One DER element at b[i:]: (tag, header length, content length)."""
    tag = b[i]; n = b[i + 1]; h = 2
    if n & 0x80:
        k = n & 0x7f; n = int.from_bytes(b[i + 2:i + 2 + k], "big"); h = 2 + k
    return tag, h, n

def children(b, i):
    """The elements inside the constructed element at b[i:], as (tag, start, end) with start at the header."""
    tag, h, n = tlv(b, i)
    out, p, end = [], i + h, i + h + n
    while p < end:
        t, hh, nn = tlv(b, p)
        out.append((t, p, p + hh + nn))
        p += hh + nn
    return out

def content(b, i):
    tag, h, n = tlv(b, i)
    return b[i + h:i + h + n]

def oid(b):
    out = [b[0] // 40, b[0] % 40]; v = 0
    for x in b[1:]:
        v = (v << 7) | (x & 0x7f)
        if not x & 0x80: out.append(v); v = 0
    return ".".join(map(str, out))

CURVES = {"1.2.840.10045.3.1.7": 23, "1.3.132.0.34": 24, "1.3.132.0.35": 25}

def anchor(der):
    cert = children(der, 0)
    tbs = children(der, cert[0][1])
    k = 1 if tbs[0][0] == 0xA0 else 0          # [0] version is optional
    subject = der[tbs[k + 4][1]:tbs[k + 4][2]]   # serial, sig alg, issuer, validity, subject, spki
    spki = children(der, tbs[k + 5][1])
    alg = children(der, spki[0][1])
    algo = oid(content(der, alg[0][1]))
    bits = content(der, spki[1][1])[1:]          # skip the unused-bits byte
    if algo == "1.2.840.113549.1.1.1":
        n, e = (content(bits, s) for _, s, _ in children(bits, 0))
        return subject, ("rsa", n.lstrip(b"\0"), e.lstrip(b"\0"))
    if algo == "1.2.840.10045.2.1":
        return subject, ("ec", CURVES[oid(content(der, alg[1][1]))], bits)
    raise SystemExit("tls-ta: unsupported key algorithm " + algo)

def pems(path):
    with open(path, "rb") as f:
        for m in re.finditer(rb"-----BEGIN CERTIFICATE-----(.*?)-----END CERTIFICATE-----", f.read(), re.S):
            yield base64.b64decode(b"".join(m.group(1).split()))

def carr(name, b):
    body = ",".join("0x%02x" % x for x in b)
    return "static const unsigned char %s[%d] = {%s};\n" % (name, len(b), body)

def header(certs):
    out = ["/* Generated by tools/gen/tls-ta.py: the embedded trust anchors. Do not edit. */\n"]
    rows = []
    for i, (dn, key) in enumerate(certs):
        out.append(carr("ta%d_dn" % i, dn))
        if key[0] == "rsa":
            out.append(carr("ta%d_n" % i, key[1])); out.append(carr("ta%d_e" % i, key[2]))
            rows.append("    {{(unsigned char *)ta%d_dn, sizeof ta%d_dn}, BR_X509_TA_CA, {BR_KEYTYPE_RSA, "
                        "{.rsa = {(unsigned char *)ta%d_n, sizeof ta%d_n, (unsigned char *)ta%d_e, sizeof ta%d_e}}}}" % ((i,) * 6))
        else:
            out.append(carr("ta%d_q" % i, key[2]))
            rows.append("    {{(unsigned char *)ta%d_dn, sizeof ta%d_dn}, BR_X509_TA_CA, {BR_KEYTYPE_EC, "
                        "{.ec = {%d, (unsigned char *)ta%d_q, sizeof ta%d_q}}}}" % (i, i, key[1], i, i))
    out.append("static const br_x509_trust_anchor TAS[%d] = {\n%s\n};\n" % (len(certs), ",\n".join(rows)))
    out.append("#define TAS_NUM %d\n" % len(certs))
    return "".join(out)

def selftest():
    # A tiny hand-built certificate skeleton: SEQ{ SEQ{ [0]ver, INT serial, SEQ alg, SEQ issuer, SEQ validity,
    # SEQ subject("CN=t"), SEQ spki{ SEQ{rsa oid, NULL}, BITSTRING{0, SEQ{INT n, INT e}} } } }
    def el(tag, body): return bytes([tag, len(body)]) + body
    rsa = el(0x30, el(0x02, b"\x00\xc3") + el(0x02, b"\x01\x00\x01"))
    spki = el(0x30, el(0x30, el(0x06, b"\x2a\x86\x48\x86\xf7\x0d\x01\x01\x01") + el(0x05, b"")) + el(0x03, b"\x00" + rsa))
    subject = el(0x30, el(0x31, el(0x30, el(0x06, b"\x55\x04\x03") + el(0x13, b"t"))))
    tbs = el(0x30, el(0xA0, el(0x02, b"\x02")) + el(0x02, b"\x01") + el(0x30, b"") + el(0x30, b"") + el(0x30, b"") + subject + spki)
    dn, key = anchor(el(0x30, tbs))
    assert dn == subject and key == ("rsa", b"\xc3", b"\x01\x00\x01"), (dn, key)
    assert "TAS_NUM 1" in header([(dn, key)])
    print("tls-ta: self-test ok")

if __name__ == "__main__":
    if len(sys.argv) < 3:
        selftest(); sys.exit(0)
    certs = [anchor(der) for p in sys.argv[2:] for der in pems(p)]
    if not certs: raise SystemExit("tls-ta: no certificates")
    with open(sys.argv[1], "w") as f:
        f.write(header(certs))
    print("tls-ta: %d trust anchors -> %s" % (len(certs), sys.argv[1]))
