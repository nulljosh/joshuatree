#!/usr/bin/env python3
"""Subset the embedded TTF faces (fontTools) and emit drivers/*_font.h byte
arrays so the kernel's runtime TTF rasterizer (drivers/ttf.c) has real fonts
to load without a filesystem. The kernel's .bss/ring-3 window only has
~227KB of headroom, so each face is subset down to ASCII + Latin-1
(U+0020-007E, U+00A0-00FF) with no hinting, not the full ~200-750KB source
files kept in tools/fonts/ for the host-check comparison against PIL.

Regenerate everything with: python3 tools/gen/gen_ttf_font.py
"""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FONTS_DIR = os.path.join(ROOT, "tools", "fonts")
DRIVERS_DIR = os.path.join(ROOT, "drivers")

UNICODES = "U+0020-007E,U+00A0-00FF"

# (source ttf, subset ttf, header, C array name, license comment)
FACES = [
    ("DejaVuSans.ttf", "DejaVuSans-subset.ttf", "dejavu_font.h",
     "dejavu_font_data", "DejaVu Sans", "DejaVu Sans is public domain / Bitstream Vera license."),
    ("DejaVuSans-Bold.ttf", "DejaVuSans-Bold-subset.ttf", "dejavu_bold_font.h",
     "dejavu_bold_font_data", "DejaVu Sans Bold", "DejaVu Sans Bold is public domain / Bitstream Vera license."),
    ("DejaVuSerif.ttf", "DejaVuSerif-subset.ttf", "dejavu_serif_font.h",
     "dejavu_serif_font_data", "DejaVu Serif", "DejaVu Serif is public domain / Bitstream Vera license."),
    ("DejaVuSerif-Bold.ttf", "DejaVuSerif-Bold-subset.ttf", "dejavu_serif_bold_font.h",
     "dejavu_serif_bold_font_data", "DejaVu Serif Bold", "DejaVu Serif Bold is public domain / Bitstream Vera license."),
    ("DejaVuSansMono.ttf", "DejaVuSansMono-subset.ttf", "dejavu_mono_font.h",
     "dejavu_mono_font_data", "DejaVu Sans Mono", "DejaVu Sans Mono is public domain / Bitstream Vera license."),
    ("DejaVuSansMono-Bold.ttf", "DejaVuSansMono-Bold-subset.ttf", "dejavu_mono_bold_font.h",
     "dejavu_mono_bold_font_data", "DejaVu Sans Mono Bold", "DejaVu Sans Mono Bold is public domain / Bitstream Vera license."),
]


def subset_font(src_path, dst_path):
    subprocess.run(
        [
            sys.executable, "-m", "fontTools.subset", src_path,
            f"--unicodes={UNICODES}", "--no-hinting", "--desubroutinize",
            "--layout-features=", f"--output-file={dst_path}",
        ],
        check=True,
    )


def write_header(dst_ttf, header_path, array_name, guard, pretty_name, license_line):
    with open(dst_ttf, "rb") as f:
        data = f.read()

    with open(header_path, "w") as f:
        f.write("/* Generated by tools/gen/gen_ttf_font.py. Do not edit by hand.\n")
        f.write(f"   {pretty_name}, embedded so ttf_load() has a font with no filesystem.\n")
        f.write(f"   {license_line} */\n")
        f.write(f"#ifndef {guard}\n#define {guard}\n\n")
        f.write(f"#define {array_name.upper()}_LEN {len(data)}u\n\n")
        f.write(f"static const unsigned char {array_name}[{array_name.upper()}_LEN] = {{\n")
        for i in range(0, len(data), 16):
            chunk = data[i:i + 16]
            f.write("    " + ",".join(str(b) for b in chunk) + ",\n")
        f.write("};\n\n#endif\n")

    print(f"wrote {header_path} ({len(data)} bytes, subset ttf {os.path.getsize(dst_ttf)} bytes)")


def main():
    total = 0
    for src_name, subset_name, header_name, array_name, pretty_name, license_line in FACES:
        src_path = os.path.join(FONTS_DIR, src_name)
        dst_path = os.path.join(FONTS_DIR, subset_name)
        subset_font(src_path, dst_path)

        header_path = os.path.join(DRIVERS_DIR, header_name)
        guard = header_name.upper().replace(".", "_")
        write_header(dst_path, header_path, array_name, guard, pretty_name, license_line)
        total += os.path.getsize(dst_path)

    print(f"total embedded font bytes: {total}")


if __name__ == "__main__":
    main()
