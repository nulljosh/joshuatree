#!/usr/bin/env python3
"""Embed tools/fonts/DejaVuSans-subset.ttf as a byte array in
drivers/dejavu_font.h so the kernel's runtime TTF rasterizer (drivers/ttf.c)
has a font to load without a filesystem. The kernel's .bss/ring-3 window
only has ~227KB of headroom, so this embeds an ASCII + Latin-1 subset
(~17KB), not the full DejaVuSans.ttf (~750KB) kept in tools/fonts/ for the
host-check comparison against PIL.

Regenerate the subset with:
  python3 -m fontTools.subset tools/fonts/DejaVuSans.ttf \\
      --unicodes=U+0020-007E,U+00A0-00FF --no-hinting --desubroutinize \\
      --layout-features='' --output-file=tools/fonts/DejaVuSans-subset.ttf
Then regenerate this header with: python3 tools/gen/gen_ttf_font.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "tools", "fonts", "DejaVuSans-subset.ttf")
DST = os.path.join(ROOT, "drivers", "dejavu_font.h")


def main():
    with open(SRC, "rb") as f:
        data = f.read()

    with open(DST, "w") as f:
        f.write("/* Generated by tools/gen/gen_ttf_font.py. Do not edit by hand.\n")
        f.write("   DejaVu Sans, embedded so ttf_load() has a font with no filesystem.\n")
        f.write("   DejaVu Sans is public domain / Bitstream Vera license. */\n")
        f.write("#ifndef DEJAVU_FONT_H\n#define DEJAVU_FONT_H\n\n")
        f.write(f"#define DEJAVU_FONT_LEN {len(data)}u\n\n")
        f.write("static const unsigned char dejavu_font_data[DEJAVU_FONT_LEN] = {\n")
        for i in range(0, len(data), 16):
            chunk = data[i:i + 16]
            f.write("    " + ",".join(str(b) for b in chunk) + ",\n")
        f.write("};\n\n#endif\n")

    print(f"wrote {DST} ({len(data)} bytes)")


if __name__ == "__main__":
    main()
