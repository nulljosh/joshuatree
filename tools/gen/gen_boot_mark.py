#!/usr/bin/env python3
"""The brand mark for the kernels: the flat glyph of the painted tree (docs/brand/glyph.png, written by
tools/gen/gen_brand_art.py from docs/brand/tree.png, 7.10).

  kernel/boot_mark.h        the i386 boot splash (160 px) and both menu bars (80 px): the glyph as 8-bit coverage, with
                            _acc the share of each pixel that is the soil, and boot_mark_rev, the frame (1..STEPS) each
                            pixel first shows in as the tree grows from its foot up, the soil last
  arch/arm64/splash_mark.h  the Pi boot splash: the same glyph at 400 px as one-colour coverage, Apple style (7.10),
                            only ever box-filtered down

Physical pixels, not logical: both splashes draw in physical pixels, so this rasterizes at the size they draw, plain
arrays with no decoder at boot.

Usage:
    python3 tools/gen/gen_boot_mark.py            # regenerate both headers
    python3 tools/gen/gen_boot_mark.py --check     # fail if either is stale
"""
import os
import sys

from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
GLYPH = os.path.join(ROOT, "docs", "brand", "glyph.png")
OUT = os.path.join(ROOT, "kernel", "boot_mark.h")
SPLASH_OUT = os.path.join(ROOT, "arch", "arm64", "splash_mark.h")

STEPS = 48      # frames of the draw-on; the kernel maps elapsed ticks onto 1..STEPS
TARGET_H = 160  # physical px, the i386 splash's tree height
SPLASH_H = 400  # the Pi splash, only ever scaled down so it stays sharp up to 1440p and beyond
SMALL = 80      # physical px: the menu bar (20 logical at scale 2) is an exact 2x2 average, the About card 32


def layers(px):
    """(coverage, soil share) of the glyph at px square: its alpha, and the part of it that is the terracotta soil."""
    g = Image.open(GLYPH).convert("RGBA").resize((px, px), Image.LANCZOS)
    cov, acc = [], []
    for r, a in zip(g.getchannel("R").tobytes(), g.getchannel("A").tobytes()):
        cov.append(a)
        acc.append(a if r > 120 else 0)   # bark ink is dark (r 38), the soil terracotta (r 181)
    return cov, acc


def reveal_map(cov, acc, w, h):
    """The tree grows from the foot of its trunk to the tips of its rosettes, then the soil washes in last."""
    rows = [y for y in range(h) if any(cov[y * w + x] and not acc[y * w + x] for x in range(w))]
    top, bot = rows[0], rows[-1]
    rev = []
    for i, (c, s) in enumerate(zip(cov, acc)):
        y = i // w
        if not c: rev.append(0)
        elif s * 2 >= c: rev.append(STEPS)
        else: rev.append(1 + (STEPS - 2) * (bot - min(y, bot)) // max(1, bot - top))
    return rev


def array(name, cov, w):
    out = [f"static const unsigned char {name}[{len(cov)}] __attribute__((unused)) = {{"]
    for i in range(0, len(cov), 20):
        out.append("    " + ",".join(str(v) for v in cov[i:i + 20]) + ",")
    out.append("};")
    return out


def main():
    w = h = TARGET_H
    cov, acc = layers(TARGET_H)
    small, small_acc = layers(SMALL)
    rev = reveal_map(cov, acc, w, h)

    lines = ["/* Generated by tools/gen/gen_boot_mark.py. Do not hand-edit. */", "#ifndef BOOT_MARK_HDR", "#define BOOT_MARK_HDR", "",
             "#define MARK_GROUND 0x001C1C1E   /* 3.0.0: flat ink; the kernels draw the glyph in one colour */", "",
             "/* The splash: docs/brand/glyph.png, the painted tree traced flat (7.10). _acc is the part of each pixel that is the soil. */",
             f"#define BOOT_MARK_W {w}", f"#define BOOT_MARK_H {h}", ""]
    lines += array("boot_mark_cov", cov, w)
    lines += array("boot_mark_acc", acc, w)
    lines += ["", "/* The draw-on: the frame (1 to BOOT_MARK_STEPS) each pixel first appears in as the tree grows up from its foot, soil last, 0 where empty. */",
              f"#define BOOT_MARK_STEPS {STEPS}"]
    lines += array("boot_mark_rev", rev, w)
    lines += ["", "/* The menu bar: the same glyph at 80 px, so it reads at 20. */", f"#define MENU_MARK_W {SMALL}", f"#define MENU_MARK_H {SMALL}", ""]
    lines += array("menu_mark_cov", small, SMALL)
    lines += array("menu_mark_acc", small_acc, SMALL)
    lines += ["", "#endif"]
    text = "\n".join(lines) + "\n"

    flat, _ = layers(SPLASH_H)
    splash = ["/* Generated by tools/gen/gen_boot_mark.py. Do not hand-edit. */", "#ifndef SPLASH_MARK_HDR", "#define SPLASH_MARK_HDR",
              "/* 7.10: the Pi boot splash's mark, Apple style: the flat glyph (docs/brand/glyph.png) at 400 px, soil and all, as",
              "   8-bit coverage drawn in one ink. Only ever box-filtered down (crash.c splash_mark), so it stays sharp at 1080p and 1440p. */",
              f"#define SPLASH_MARK_W {SPLASH_H}", f"#define SPLASH_MARK_H {SPLASH_H}"]
    splash += array("splash_mark_cov", flat, SPLASH_H)
    splash_text = "\n".join(splash + ["#endif"]) + "\n"

    if "--check" in sys.argv:
        for path, want in ((OUT, text), (SPLASH_OUT, splash_text)):
            cur = open(path).read() if os.path.exists(path) else ""
            if cur != want:
                print(f"{os.path.relpath(path, ROOT)} is stale, run tools/gen/gen_boot_mark.py", file=sys.stderr)
                sys.exit(1)
        print("kernel/boot_mark.h and arch/arm64/splash_mark.h up to date")
        return

    with open(OUT, "w") as f:
        f.write(text)
    with open(SPLASH_OUT, "w") as f:
        f.write(splash_text)
    print(f"wrote {OUT}: splash {w}x{h}, menu bar {SMALL}x{SMALL}; {SPLASH_OUT}: flat glyph {SPLASH_H} px")


if __name__ == "__main__":
    main()
