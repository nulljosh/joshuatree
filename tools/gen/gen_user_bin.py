#!/usr/bin/env python3
"""Turn a built flat user binary into a C byte array the kernel can seed
into the VFS.

The kernel has to be able to run the reference program on a machine with
no disk at all, which is the exact condition the browser embed and every
headless check boot under (see tools/checks/ramfs-demo-check.sh). So the
binary rides along inside kernel.elf as bytes and `usertest` writes it out
through vfs_write_file() before exec'ing it. That is still a real VFS load:
exec_user() reads it back with vfs_read_file() and knows nothing about
where it came from.

Same "generated header, regenerated by the Makefile" relationship the
app_*.h and png_testdata.h headers already have.
"""
import sys

src, out, name = sys.argv[1], sys.argv[2], sys.argv[3]
data = open(src, 'rb').read()
guard = name.upper() + '_H'

with open(out, 'w') as f:
    f.write('#ifndef %s\n#define %s\n' % (guard, guard))
    f.write('/* Generated by tools/gen/gen_user_bin.py from %s. Do not edit. */\n' % src)
    f.write('static const unsigned char %s[] = {\n' % name)
    for i in range(0, len(data), 12):
        f.write('    ' + ''.join('0x%02x, ' % b for b in data[i:i + 12]).rstrip() + '\n')
    f.write('};\n')
    f.write('#define %s_LEN %du\n' % (name.upper(), len(data)))
    f.write('#endif\n')

print('%s: %d bytes' % (out, len(data)))
