#!/usr/bin/env python3
"""Turn a built flat user binary into a compressed C byte array the kernel
can unpack into the VFS.

The kernel has to be able to run the reference program on a machine with
no disk at all, which is the exact condition the browser embed and every
headless check boot under (see tools/checks/ramfs-demo-check.sh). So the
binary rides along inside kernel.elf as bytes and ring3app_seed() writes it
out through vfs_write_file() before exec'ing it. That is still a real VFS
load: exec_user() reads it back with vfs_read_file() and knows nothing about
where it came from.

2.7.1: the bytes are raw deflate (zlib level 9, wbits -15), not the plain
binary. Twenty-odd apps of 20 to 80 KB each had eaten the gap between .bss
and the ring-3 window; compressed they take about half. The header carries:
  <name>[]            the compressed bytes
  <NAME>_LEN          the RAW length (what it always meant)
  <NAME>_CLEN         the compressed length
  <NAME>_SUM          Adler-32 of the RAW bytes, checked after inflating
ring3app.c refuses to start an app whose length or sum does not match.

Same "generated header, regenerated by the Makefile" relationship the
app_*.h and png_testdata.h headers already have.
"""
import sys, zlib


def pack(data):
    """Raw deflate at level 9. Returns the compressed bytes."""
    c = zlib.compressobj(9, zlib.DEFLATED, -15, 9)
    return c.compress(data) + c.flush()


def main():
    src, out, name = sys.argv[1], sys.argv[2], sys.argv[3]
    data = open(src, 'rb').read()
    comp = pack(data)
    guard = name.upper() + '_H'
    up = name.upper()

    with open(out, 'w') as f:
        f.write('#ifndef %s\n#define %s\n' % (guard, guard))
        f.write('/* Generated by tools/gen/gen_user_bin.py from %s. Do not edit. */\n' % src)
        f.write('/* Raw deflate of the binary; %s_LEN is the raw length, %s_SUM its Adler-32. */\n' % (up, up))
        f.write('static const unsigned char %s[] = {\n' % name)
        for i in range(0, len(comp), 12):
            f.write('    ' + ''.join('0x%02x, ' % b for b in comp[i:i + 12]).rstrip() + '\n')
        f.write('};\n')
        f.write('#define %s_LEN %du\n' % (up, len(data)))
        f.write('#define %s_CLEN %du\n' % (up, len(comp)))
        f.write('#define %s_SUM 0x%08xu\n' % (up, zlib.adler32(data) & 0xFFFFFFFF))
        f.write('#endif\n')

    print('%s: %d bytes raw, %d compressed' % (out, len(data), len(comp)))


if __name__ == '__main__':
    main()
