"""The baked wallpaper photo: pack it into drivers/wallpaper.h, or read its raw RGB back out.

4.23.0: the header holds the photo up-filtered (each byte minus the one a row above, as PNG's Up filter) and
deflated, about 520KB in place of 1.5MB of raw RGB. The kernel unpacks it the first time something shows it
(kernel.c's wall_photo_get). Tools and checks that need the pixels call wallpaper_rgb().
"""
import os, re, zlib

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HDR = os.path.join(ROOT, "drivers", "wallpaper.h")


def wallpaper_rgb(path=HDR):
    """The photo as raw RGB bytes, rows top-down, WALLPAPER_W * WALLPAPER_H * 3 long."""
    hdr = open(path).read()
    w = int(re.search(r"#define WALLPAPER_W (\d+)", hdr).group(1))
    h = int(re.search(r"#define WALLPAPER_H (\d+)", hdr).group(1))
    body = hdr[hdr.index("{") + 1:hdr.rindex("}")]
    f = zlib.decompress(bytes(int(t) for t in body.replace("\n", "").split(",") if t.strip()))
    row, out, prev = w * 3, bytearray(), bytes(w * 3)
    for y in range(h):
        prev = bytes((a + b) & 255 for a, b in zip(f[y * row:(y + 1) * row], prev))
        out += prev
    assert len(out) == w * h * 3
    return bytes(out)


def write_header(rgb, w, h, path=HDR):
    """Up-filter and deflate raw RGB into drivers/wallpaper.h."""
    row, f, prev = w * 3, bytearray(), bytes(w * 3)
    for y in range(h):
        cur = rgb[y * row:(y + 1) * row]
        f += bytes((a - b) & 255 for a, b in zip(cur, prev))
        prev = cur
    z = zlib.compress(bytes(f), 9)
    with open(path, "w") as out:
        out.write("#ifndef WALLPAPER_HDR_H\n#define WALLPAPER_HDR_H\n")
        out.write("/* Generated by tools/gen/wallraw.py: the photo, up-filtered and deflated. Read it with wallpaper_rgb(). */\n")
        out.write(f"#define WALLPAPER_W {w}\n#define WALLPAPER_H {h}\n#define WALLPAPER_Z_LEN {len(z)}\n")
        out.write("static const unsigned char wallpaper_z[] = {\n")
        for i in range(0, len(z), 24):
            out.write(",".join(str(b) for b in z[i:i + 24]) + ",\n")
        out.write("};\n#endif\n")
    return len(z)
