#!/usr/bin/env python3
"""The Pi's default wallpaper: Joshua Tree National Park at dusk (8.9.0, Joshua's ask). Since 13.27.0 it is a painting in the
spirit of Surenix's Ayeris wallpapers, soft and matte with a fine grain (art/wallpaper/park-dusk.jpg, 1920 x 1080, made with
Higgsfield from the old pixel scene), not the 16-colour dithered pixel scene with scanlines this script used to draw.
For the Pi it is scaled to 960 x 540 and reduced to 256 colours with error diffusion, one byte a pixel; the screen shows it 2x.
13.27.3: the pixels are stored deflated (park_z, 168 KB, not 518 KB raw), so kernel8.img fits the 3.9 MiB a Pi's `update`
can fetch; wall.c unpacks them once with drivers/inflate.c. Writes arch/arm64/park_wall.h (PARK_W, PARK_H, park_pal[256],
PARK_Z_SUM, park_z) and
the 1920 x 1080 brand copy docs/brand/park-wall.png (or the path given), which the README banner and the landing read.
Usage: tools/gen/gen_park_wall.py [preview.png]"""
import sys, zlib
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parents[2]
W, H = 960, 540
src = Image.open(root / "art/wallpaper/park-dusk.jpg").convert("RGB")
small = src.resize((W, H), Image.LANCZOS).quantize(256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.FLOYDSTEINBERG)
pal = small.getpalette()[:768]; pal += [0] * (768 - len(pal))
px = small.tobytes()
def deflate(b):
    c = zlib.compressobj(9, zlib.DEFLATED, -15); return c.compress(b) + c.flush()
z = deflate(px)
rows = ["/* GENERATED by tools/gen/gen_park_wall.py from art/wallpaper/park-dusk.jpg -- do not edit. 256 colours, a byte a pixel,",
        "   stored as raw deflate (13.27.3); PARK_Z_SUM is the Adler-32 of the unpacked pixels. */",
        "#define PARK_W %d" % W, "#define PARK_H %d" % H,
        "static const unsigned park_pal[256] = { %s };" % ", ".join("0x00%02X%02X%02Xu" % tuple(pal[i * 3:i * 3 + 3]) for i in range(256)),
        "#define PARK_Z_SUM 0x%08Xu" % zlib.adler32(px),
        "static const unsigned char park_z[%d] = {" % len(z)]
for i in range(0, len(z), 400):   # long rows: the header stays under godfile-check.sh's line ceiling
    rows.append("    " + ",".join(str(b) for b in z[i:i + 400]) + ",")
rows.append("};")
(root / "arch/arm64/park_wall.h").write_text("\n".join(rows) + "\n")
src.save(sys.argv[1] if len(sys.argv) > 1 else root / "docs/brand/park-wall.png", optimize=True)
print("wrote arch/arm64/park_wall.h (%d x %d, 256 colours, %d bytes deflated) and the 1920 x 1080 brand copy" % (W, H, len(z)))
