#!/usr/bin/env python3
"""Write docs/TESTING.md from the suite itself, so the doc can't drift.

Every line of tools/checks/ci-suite.sh becomes a row (what it proves, the
file that proves it). Then each app in kernel.c's APPS[] registry gets the
checks that name it, so the apps with no test stand out. --check exits 1
when the committed doc is stale (tools/checks/testing-doc-check.sh runs it).
"""
import os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
suite = open(os.path.join(ROOT, "tools/checks/ci-suite.sh")).read()
rows = re.findall(r"^(once|retry)\s*\|(\d+)\|([^|]+)\|(.+)$", suite, re.M)
kernel_src = open(os.path.join(ROOT, "kernel/kernel.c")).read()
table = re.search(r"static const struct app APPS\[GUI_APP_COUNT\] = \{(.*?)\n\};", kernel_src, re.S)
apps = re.findall(r'\{\s*"([^"]+)"', table.group(1))


def file_of(cmd):
    m = re.search(r"(tools/checks/[\w.-]+|check\.sh)", cmd)
    return m.group(1) if m else cmd.strip()


out = ["# Testing", "",
       "Every check the suite runs, what it proves, and which apps still have none.",
       "Generated by `tools/gen/testing-doc.py` from `tools/checks/ci-suite.sh`; don't edit by hand.",
       "", "Run it all locally with `tools/ci-local.sh`. Run one with the command in the table.", "",
       f"## The suite ({len(rows)} checks)", "", "| What it proves | File | Mode |", "|---|---|---|"]
for mode, _, desc, cmd in rows:
    out.append(f"| {desc.strip()} | `{file_of(cmd)}` | {mode} |")
out += ["", "`retry` checks boot a VM and get one retry for host timing noise; `once` checks are pure and never retried.", "",
        "## Apps", "", "| App | Checks that name it |", "|---|---|"]
missing = []
for app in apps:
    key = app.lower()
    hits = [file_of(c) for _, _, d, c in rows if key in d.lower() or key in c.lower()]
    if not hits:
        missing.append(app)
    out.append(f"| {app} | {', '.join(f'`{h}`' for h in sorted(set(hits))) or 'none yet'} |")
out += ["", f"Apps with no check yet: {', '.join(missing) if missing else 'none'}.", ""]
text = "\n".join(out)
path = os.path.join(ROOT, "docs/TESTING.md")
if "--check" in sys.argv:
    if not os.path.exists(path) or open(path).read() != text:
        sys.exit("FAIL: docs/TESTING.md is stale; run tools/gen/testing-doc.py")
    print(f"PASS: docs/TESTING.md lists all {len(rows)} checks")
else:
    open(path, "w").write(text)
    print(f"testing-doc: {len(rows)} checks, {len(apps) - len(missing)}/{len(apps)} apps covered; none yet: {', '.join(missing)}")
