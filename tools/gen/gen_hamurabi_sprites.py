#!/usr/bin/env python3
"""Turns art/hamurabi/sprites.png and sprites.json into user/hamurabi_sprites.h, plain C data for the Hamurabi app.

Run from the repo root:  python3 tools/gen/gen_hamurabi_sprites.py            (rewrite the header)
                         python3 tools/gen/gen_hamurabi_sprites.py --check    (fail if the header is stale)

The sheet is one 256x149 picture holding every sprite. It is stored as
  - a palette of 0xAARRGGBB words (index 0 is the fully transparent pixel; the 27 half-see-through
    shades the shadows and ghosts use keep their alpha, the app blends them),
  - the sheet as palette indices, run-length coded as (count 1..255, index) byte pairs, row after row,
  - a table of sprite rectangles with an enum, so C can say HAM_SPR_KING_0.
The app unpacks the runs into a 38 KB index image on its heap, so the flat binary stays small.
The art itself is drawn by ~/Documents/Code/hamurabi/art/build.py; the two files are copied here as they are."""
import json, os, sys
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
OUT = os.path.join(ROOT, "user", "hamurabi_sprites.h")
LOOKS = "abcdefghijkl"


def build():
    im = Image.open(os.path.join(ROOT, "art", "hamurabi", "sprites.png")).convert("RGBA")
    spr = json.load(open(os.path.join(ROOT, "art", "hamurabi", "sprites.json")))
    w, h = im.size
    px = list(im.getdata()) if not hasattr(im, "get_flattened_data") else list(im.get_flattened_data())
    # Every fully transparent pixel is the same colour to the app, whatever RGB the PNG hid in it.
    px = [(0, 0, 0, 0) if p[3] == 0 else p for p in px]
    palette = [(0, 0, 0, 0)] + sorted(set(px) - {(0, 0, 0, 0)})
    index = {c: i for i, c in enumerate(palette)}
    if len(palette) > 256:
        sys.exit("more than 256 colours: the sheet no longer fits 8-bit indices")
    for name, (x, y, rw, rh) in spr.items():
        if x < 0 or y < 0 or x + rw > w or y + rh > h:
            sys.exit("sprite %s lies outside the %dx%d sheet" % (name, w, h))
    data = bytearray()
    flat = [index[p] for p in px]
    i = 0
    while i < len(flat):
        j = i
        while j < len(flat) and flat[j] == flat[i] and j - i < 255:
            j += 1
        data += bytes((j - i, flat[i]))
        i = j

    o = []
    a = o.append
    a("/* Generated by tools/gen/gen_hamurabi_sprites.py from art/hamurabi/sprites.png and sprites.json. Do not edit by hand. */")
    a("#ifndef HAMURABI_SPRITES_H\n#define HAMURABI_SPRITES_H\n")
    a("#define HAM_SHEET_W %d\n#define HAM_SHEET_H %d\n#define HAM_PAL_N %d\n" % (w, h, len(palette)))
    a("/* 0xAARRGGBB. Index 0 is transparent; alpha 240 is a shadow or ghost shade to blend. */")
    a("static const unsigned int ham_palette[HAM_PAL_N] = {")
    for k in range(0, len(palette), 8):
        a("    " + ", ".join("0x%02X%02X%02X%02X" % (c[3], c[0], c[1], c[2]) for c in palette[k:k + 8]) + ",")
    a("};\n")
    a("/* The sheet as (run length 1..255, palette index) pairs, row after row, %d pairs for %d pixels. */" % (len(data) // 2, w * h))
    a("#define HAM_SHEET_RLE_LEN %d" % len(data))
    a("static const unsigned char ham_sheet_rle[HAM_SHEET_RLE_LEN] = {")
    for k in range(0, len(data), 24):
        a("    " + ",".join(str(b) for b in data[k:k + 24]) + ",")
    a("};\n")
    names = list(spr)
    a("enum {")
    for n in names:
        a("    HAM_SPR_%s," % n.upper())
    a("    HAM_SPR_COUNT\n};\n")
    a("/* x, y, width, height on the sheet, in enum order. */")
    a("static const short ham_spr[HAM_SPR_COUNT][4] = {")
    for n in names:
        a("    { %d, %d, %d, %d }, /* %s */" % (*spr[n], n))
    a("};\n")
    a("/* The twelve villager looks a..l: four walking frames, two cheering frames. */")
    a("#define HAM_LOOKS %d" % len(LOOKS))
    a("static const unsigned char ham_villager[HAM_LOOKS][4] = {")
    for l in LOOKS:
        a("    { %s }," % ", ".join("HAM_SPR_VILLAGER_%s_%d" % (l.upper(), k) for k in range(4)))
    a("};")
    a("static const unsigned char ham_cheer[HAM_LOOKS][2] = {")
    for l in LOOKS:
        a("    { %s }," % ", ".join("HAM_SPR_CHEER_%s_%d" % (l.upper(), k) for k in range(2)))
    a("};\n")
    a("#endif\n")
    return "\n".join(o), len(palette), len(data), len(names)


def main():
    text, npal, nrle, nspr = build()
    if "--check" in sys.argv:
        have = open(OUT).read() if os.path.exists(OUT) else ""
        if have != text:
            print("FAIL: user/hamurabi_sprites.h is stale, run tools/gen/gen_hamurabi_sprites.py and commit it")
            return 1
        print("PASS: user/hamurabi_sprites.h matches art/hamurabi/sprites.png and sprites.json")
        return 0
    open(OUT, "w").write(text)
    print("wrote %s: %d sprites, %d palette entries, sheet %d bytes as runs (raw would be 38144)" % (OUT, nspr, npal, nrle))
    return 0


if __name__ == "__main__":
    sys.exit(main())
