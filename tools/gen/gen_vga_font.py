#!/usr/bin/env python3
"""Generates drivers/vgafont.h: a 1-bit 8x16 fallback font for the kernel.

font.c's real font comes from VGA hardware, where a PC BIOS leaves the
CP437 glyph set in plane 2. That works on real hardware and under QEMU. It
does not work under v86, the JS/wasm emulator the landing page demo runs
on, because v86 has no BIOS to have put anything there: the dump comes back
as 4096 zero bytes, so every glyph is blank and NO text renders anywhere in
the demo (measured, not guessed: a serial probe reported FONT=2320 non-zero
bytes under QEMU and FONT=0 under v86). That is the same class of bug as
v16/v17/v18, each of which was some piece of state a real BIOS sets up and
v86 simply never does.

This is the one place a bitmap is unavoidable and correct: a font IS glyph
bitmaps. It does not weaken the no-bitmap rule for icons, which stay real
vector geometry.

ASCII 32..126 only. Everything outside that stays blank, matching what
html.c already guarantees it will ever ask to draw.
"""
import os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "drivers", "vgafont.h")
TTF = os.path.join(HERE, "..", "fonts", "DejaVuSansMono.ttf")

FIRST, LAST, W, H = 32, 126, 8, 16

# Size chosen by measuring, not by eye: the largest size whose widest
# printable glyph still fits in 8px, so nothing is clipped mid-stroke.
font = ImageFont.truetype(TTF, 14)

rows = []
for code in range(FIRST, LAST + 1):
    img = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(img)
    d.text((0, -1), chr(code), fill=255, font=font)
    px = img.load()
    glyph = []
    for y in range(H):
        bits = 0
        for x in range(W):
            # 1-bit: the VGA font this stands in for has no antialiasing,
            # and font_draw_char reads it one bit per pixel.
            if px[x, y] > 110:
                bits |= 1 << (7 - x)
        glyph.append(bits)
    rows.append((code, glyph))

with open(OUT, "w") as f:
    f.write("#ifndef VGAFONT_H\n#define VGAFONT_H\n")
    f.write("/* Generated by tools/gen/gen_vga_font.py. Fallback only: used when the\n"
            "   real VGA hardware font comes back empty (no BIOS, e.g. v86).\n"
            "   ASCII %d..%d, 8x16, one bit per pixel, MSB leftmost. */\n" % (FIRST, LAST))
    f.write("#define VGAFONT_FIRST %d\n#define VGAFONT_LAST %d\n" % (FIRST, LAST))
    f.write("static const unsigned char vgafont_glyphs[] = {\n")
    for code, glyph in rows:
        f.write("    " + ",".join(str(b) for b in glyph) + ", /* %d %r */\n" % (code, chr(code)))
    f.write("};\n#endif\n")

print("wrote %s (%d glyphs)" % (OUT, len(rows)))
